def get_kp_learning_order():
    """拓扑排序，按 KP 依赖关系返回学习顺序"""
    from collections import deque, defaultdict

    in_degree = defaultdict(int)
    graph = defaultdict(list)

    for kp_id, kp in KPS.items():
        in_degree[kp_id] = len(kp['prereq'])
        for pre in kp['prereq']:
            graph[pre].append(kp_id)

    queue = deque([k for k in KPS if in_degree[k] == 0])
    order = []
    while queue:
        # 同 tier 内按 id 排序
        queue = deque(sorted(queue, key=lambda x: (KPS[x]['tier'], x)))
        u = queue.popleft()
        order.append(u)
        for v in graph[u]:
            in_degree[v] -= 1
            if in_degree[v] == 0:
                queue.append(v)

    return order


def get_kp_learning_order_by_tier():
    """按 tier 分层、层内拓扑序的友好顺序"""
    # 先做完整拓扑序
    full_order = get_kp_learning_order()
    # 提取每个 KP 的"实际可学时间"（即它在拓扑序中的位置）
    pos = {kp: i for i, kp in enumerate(full_order)}
    # 然后按 (tier, pos) 排序
    return sorted(full_order, key=lambda k: (KPS[k]['tier'], pos[k]))


